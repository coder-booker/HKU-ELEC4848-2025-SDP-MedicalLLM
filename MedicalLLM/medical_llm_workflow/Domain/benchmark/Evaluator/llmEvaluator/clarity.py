"""Clarity 评估器实现。"""
from __future__ import annotations

import json
import re
from typing import Any, Dict, List, Tuple

from medical_llm_workflow.Domain.benchmark.Evaluator.base_evaluator import BaseEvaluator
from medical_llm_workflow.Domain.benchmark.Evaluator.models import (
    EvaluatorType,
    EvluationRecord,
)
from medical_llm_workflow.Infrastructure.LLM_client.client_factory import ClientFactory
from medical_llm_workflow.Infrastructure.LLM_client.models import ChatbotType, PoeChatbotModel
from medical_llm_workflow.Infrastructure.llm_json_utils import call_llm_with_json_retry
from medical_llm_workflow.schemas.models import ConversationMessageRole, ConversationMessageStatus


class ClarityEvaluator(BaseEvaluator):
    """
    Clarity 评估器。
    
    使用 LLM 作为评委 (LLM-as-a-judge)，
    分析模型输出推理文本的表达清晰程度（Clarity），即文本表述是否清晰易懂。
    由于只针对文本本身质量进行判断，所以只提供预测文本即可（可提供 Ground truth 作为医学难度或上下文参考，但主要基于 Pred 本身）。
    """

    evaluator_name = "clarity_evaluator"
    metric_name = EvaluatorType.CLARITY.value
    
    # 要求从 SmartExtractor 提取的字段
    protocol: Dict[str, str] = {
        "reasoning_process": "<Provide the reasoning text steps strictly from the generated output>",
    }

    async def _call_llm_judge(
        self, 
        pred_text: str, 
        gold_text: str,
    ) -> Tuple[float, Dict[str, Any]]:
        """调用大模型进行清晰度打分。"""
        if not pred_text:
            return 0.0, {
                "llm_prompt": "[SKIPPED] Missing prediction text for clarity evaluation.",
                "llm_response": "{\"score\": 1}"
            }

        prompt = f"""
You are an expert medical evaluator. Please rate the following reasoning process generated by an AI model regarding its clarity.

Clarity definition:
Is the reasoning clearly expressed, easy to understand, and well-structured? Does it explain medical concepts effectively without causing confusion?

Score from 1 to 5:
1 = Very poor clarity, disjointed, confusing, or mostly incomprehensible.
3 = Moderate clarity, generally understandable but has poorly structured sections or jargon without context.
5 = Excellent clarity, perfectly structured, highly readable, and exceptionally clear.

Context Reference (Ground Truth):
{gold_text}

AI Reasoning Process to Evaluate:
{pred_text}

Output format ONLY: Provide a single JSON object containing integer "score" from 1 to 5.
Example: {{"score": 5}}
"""
        
        messages = [
            {
                "role": ConversationMessageRole.SYSTEM,
                "content": "You are an expert medical evaluator. Please output ONLY a valid JSON object.",
                "status": ConversationMessageStatus.NORMAL,
            },
            {
                "role": ConversationMessageRole.USER,
                "content": prompt,
                "status": ConversationMessageStatus.NORMAL,
            },
        ]

        chatbot_config = self.chatbot_config
        client = ClientFactory.get_client_instance(chatbot_config.get("chatbot_type", ChatbotType.POE))
        
        try:
            parsed_data = await call_llm_with_json_retry(
                client=client,
                messages=messages,
                chatbot_config=chatbot_config,
                max_retries=1,
            )
            
            if "error" in parsed_data:
                return 0.0, {
                    "llm_prompt": prompt,
                    "llm_response": f"[ERROR] Failed to fetch valid LLM json response: {parsed_data['error']}",
                }
            
            score = float(parsed_data.get("score", 0.0))
            
            # BaseEvaluator 强制到 [0.0, 1.0] 的归一化
            score = max(1.0, min(5.0, score))
            return score / 5.0, {
                "llm_prompt": prompt,
                "llm_response": json.dumps(parsed_data, ensure_ascii=False),
            }
            
        except Exception as e:
            # 卫语句兜底抛出异常给前端感知
            return 0.0, {
                "llm_prompt": prompt,
                "llm_response": f"[ERROR] Unexpected clarity evaluator exception: {str(e)}",
                "llm_response": f"[ERROR] Failed to fetch LLM response: {str(e)}"
            }

    async def default_compare(
        self,
        llm_output_dict: Dict[str, Any],
        dataset_ground_truth_dict: Dict[str, Any],
    ) -> Tuple[float, Dict[str, Any]]:
        """
        异步调用打分，并映射计算结果。
        """
        pred_text = llm_output_dict.get("reasoning_process", "")
        gold_text = dataset_ground_truth_dict.get("reasoning_process", "")

        score, detail = await self._call_llm_judge(pred_text, gold_text)
        
        return score, detail

    def _build_summary(
        self,
        records: List[EvluationRecord],
    ) -> Dict[str, Any]:
        """
        构建摘要信息。
        """
        summary = super()._build_summary(
            records,
        )
        
        total_samples = summary.get("total_samples", len(records))
        avg_score = 0.0
        
        if total_samples > 0:
            avg_score = sum(r["score"] for r in records) / total_samples
            
        summary["average_clarity_score_percentage"] = avg_score
        
        return summary
