"""Consistency 评估器实现。"""
from __future__ import annotations

import json
import logging
import re
from typing import Any, Dict, List, Tuple

from medical_llm_workflow.Domain.benchmark.Evaluator.base_evaluator import BaseEvaluator
from medical_llm_workflow.Domain.benchmark.Evaluator.models import (
    EvaluatorType,
    EvluationRecord,
)
from medical_llm_workflow.Infrastructure.LLM_client.client_factory import ClientFactory
from medical_llm_workflow.Infrastructure.LLM_client.models import ChatbotType, PoeChatbotModel
from medical_llm_workflow.Infrastructure.llm_json_utils import call_llm_with_json_retry
from medical_llm_workflow.schemas.models import ConversationMessageRole, ConversationMessageStatus


class ConsistencyEvaluator(BaseEvaluator):
    """
    Consistency 评估器。
    
    使用 LLM 作为评委 (LLM-as-a-judge)，
    评估模型输出的 reasoning_process 与标准答案的 long_answer（或 ground_truth）的内容
    是否保持一致，是否存在自相矛盾的情况。
    """

    evaluator_name = "consistency_evaluator"
    metric_name = EvaluatorType.CONSISTENCY.value
    
    # 告诉 SmartExtractor 提取时的 schema
    protocol: Dict[str, str] = {
        "reasoning_process": "<Provide the reasoning text steps strictly from the generated output>",
    }

    async def _call_llm_judge(
        self, 
        pred_text: str, 
        gold_text: str,
    ) -> Tuple[float, Dict[str, Any]]:
        """调用大模型作为法官进行的一致性打分"""
        if not pred_text or not gold_text:
            return 0.0, {
                "llm_prompt": "[SKIPPED] Missing prediction or ground truth text for evaluation.",
                "llm_response": "{\"score\": 1}"
            }

        prompt = f"""
You are an expert medical evaluator. Please rate the following reasoning process generated by an AI model against the ground truth reference text.
Your task is to judge the "Consistency" of the reasoning process. 

Consistency definition:
Does the reasoning closely follow and align with the facts, logic, and conclusions presented in the ground truth? Are there any self-contradictions or statements that oppose the known truth?

Score from 1 to 5:
1 = Completely inconsistent, contradictory, or hallucinates significantly against the truth.
3 = Partially consistent, some parts align but there are notable deviations or missing key logic.
5 = Perfectly consistent, reasoning logically aligns with the ground truth without contradiction.

Ground Truth Reference:
{gold_text}

AI Reasoning Process to Evaluate:
{pred_text}

Output format ONLY: Provide a single JSON object containing integer "score" from 1 to 5.
Example: {{"score": 5}}
"""
        
        # 调用由 ClientFactory 构建的 client
        
        messages = [
            {
                "role": ConversationMessageRole.SYSTEM,
                "content": "You are an expert medical evaluator. Please output ONLY a valid JSON object.",
                "status": ConversationMessageStatus.NORMAL,
            },
            {
                "role": ConversationMessageRole.USER,
                "content": prompt,
                "status": ConversationMessageStatus.NORMAL,
            },
        ]

        # 复用 BaseEvaluator 初始化时传入的 chatbot_config (若前端未传则使用默认值)
        chatbot_config = self.chatbot_config

        # 始终用配置里指定的 Provider 取 Client
        client = ClientFactory.get_client_instance(chatbot_config.get("chatbot_type", ChatbotType.POE))
        
        try:
            parsed_data = await call_llm_with_json_retry(
                client=client,
                messages=messages,
                chatbot_config=chatbot_config,
                max_retries=1,
            )
            
            if "error" in parsed_data:
                return 0.0, {
                    "llm_prompt": prompt,
                    "llm_response": f"[ERROR] Failed to fetch valid LLM response: {parsed_data['error']}",
                }
            
            score = float(parsed_data.get("score", 0.0))
            
            # BaseEvaluator中分数在 [0, 1]，而我们给出的是 1-5，因此进行归一化。
            score = max(1.0, min(5.0, score))
            return score / 5.0, {
                "llm_prompt": prompt,
                "llm_response": json.dumps(parsed_data, ensure_ascii=False),
            }
            
        except Exception as e:
            # 卫语句：兜底异常
            return 0.0, {
                "llm_prompt": prompt,
                "llm_response": f"[ERROR] Unexpected evaluator exception: {str(e)}",
            }

    async def default_compare(
        self,
        llm_output_dict: Dict[str, Any],
        dataset_ground_truth_dict: Dict[str, Any],
    ) -> Tuple[float, Dict[str, Any]]:
        """
        单条样本级比对函数。异步执行 LLM 打分。
        """
        # 前文映射中 PUBMED 选择了 "long_answer" 对应 "reasoning_process"，因此：
        pred_text = llm_output_dict.get("reasoning_process", "")
        
        # Datast Adaptor 会将 long_answer 对应到 evaluation_schema (即 reasoning_process 这个 key 上)
        gold_text = dataset_ground_truth_dict.get("reasoning_process", "")

        score, detail = await self._call_llm_judge(pred_text, gold_text)
        
        return score, detail

    def _build_summary(
        self,
        records: List[EvluationRecord],
    ) -> Dict[str, Any]:
        """
        构建评估摘要信息。
        """
        summary = super()._build_summary(
            records,
        )
        
        total_samples = summary.get("total_samples", len(records))
        avg_score = 0.0
        
        if total_samples > 0:
            # 这里的 record score 是 0-1 的
            avg_score = sum(r["score"] for r in records) / total_samples
            
        summary["average_consistency_score_percentage"] = avg_score
        
        return summary
